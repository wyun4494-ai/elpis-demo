USE elpis_beta;

-- ================================================================
-- 1. 添加新字段到 t_user 表
-- ================================================================
ALTER TABLE `t_user`
ADD COLUMN `email` VARCHAR(255) COMMENT '邮箱地址' AFTER `nickname`,
ADD COLUMN `last_login_time` DATETIME COMMENT '最后登录时间' AFTER `update_time`;

-- ================================================================
-- 2. 添加邮箱唯一性约束（支持软删除）
-- ================================================================
ALTER TABLE `t_user`
ADD UNIQUE KEY `uk_t_user_email_status` (`email`, `status`);

-- ================================================================
-- 3. 添加索引优化查询性能
-- ================================================================
ALTER TABLE `t_user`
ADD INDEX `idx_t_user_email` (`email`),
ADD INDEX `idx_t_user_last_login_time` (`last_login_time`);

-- ================================================================
-- 4. 验证修改结果
-- ================================================================
DESCRIBE `t_user`;

-- ================================================================
-- 脚本执行完成
-- ================================================================
SELECT '用户表扩展完成！新增字段：email、last_login_time' AS message;
